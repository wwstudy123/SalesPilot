def load_seed(store: KnowledgeStore) -> dict:
    """灌入种子并原子发布（幂等：重跑版本 +1，检索无中断）。

    每条话术/产品独立成文档：引用角标精确到条，标题即场景名。
    """
    published = []
    for title, content in PLAYBOOKS:
        source = f"seed-playbook-{title}"
        store.ingest("playbook", title, source, [content])
        published.append(store.publish("playbook", source))
    for title, content in PRODUCTS:
        source = f"seed-product-{title}"
        store.ingest("product", title, source, [content])
        published.append(store.publish("product", source))
    return {"published": len(published), "stats": store.stats()}
